-- Esquema de Entre Montañas para Supabase (Postgres).
-- El servidor lo ejecuta solo al arrancar; es seguro correrlo varias veces.
-- También puedes pegarlo en Supabase → SQL Editor.

CREATE TABLE IF NOT EXISTS mesas (
  id        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sucursal  text    NOT NULL,
  numero    integer NOT NULL,
  nombre    text,
  codigo    text    NOT NULL UNIQUE,
  activa    boolean NOT NULL DEFAULT true,
  UNIQUE (sucursal, numero)
);

CREATE TABLE IF NOT EXISTS categorias (
  id       text PRIMARY KEY,
  nombre   text NOT NULL,
  servicio text,
  nota     text,
  orden    integer NOT NULL
);

CREATE TABLE IF NOT EXISTS platillos (
  id          text PRIMARY KEY,
  categoria   text    NOT NULL REFERENCES categorias(id),
  nombre      text    NOT NULL,
  descripcion text,
  precio      integer NOT NULL,
  imagen      text,
  variantes   jsonb,
  elegir      jsonb,
  extras      jsonb,
  destacado   boolean NOT NULL DEFAULT false,
  disponible  boolean NOT NULL DEFAULT true,
  orden       integer NOT NULL
);

CREATE TABLE IF NOT EXISTS pedidos (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sucursal    text        NOT NULL,
  mesa_id     integer     NOT NULL REFERENCES mesas(id),
  estado      text        NOT NULL DEFAULT 'nuevo',
  cliente     text,
  nota        text,
  total       integer     NOT NULL,
  dia         date        NOT NULL,
  creado      timestamptz NOT NULL DEFAULT now(),
  actualizado timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS pedidos_estado ON pedidos (sucursal, estado);
CREATE INDEX IF NOT EXISTS pedidos_dia    ON pedidos (dia);
CREATE INDEX IF NOT EXISTS pedidos_mesa   ON pedidos (mesa_id, estado);

CREATE TABLE IF NOT EXISTS pedido_lineas (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pedido_id   integer NOT NULL REFERENCES pedidos(id) ON DELETE CASCADE,
  platillo_id text    NOT NULL,
  nombre      text    NOT NULL,
  variante    text,
  detalle     text,
  precio      integer NOT NULL,
  cantidad    integer NOT NULL,
  nota        text
);
CREATE INDEX IF NOT EXISTS pedido_lineas_pedido ON pedido_lineas (pedido_id);

CREATE TABLE IF NOT EXISTS llamadas (
  id       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sucursal text        NOT NULL,
  mesa_id  integer     NOT NULL REFERENCES mesas(id),
  tipo     text        NOT NULL,
  estado   text        NOT NULL DEFAULT 'abierta',
  creado   timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS reservas (
  id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo       text        NOT NULL UNIQUE,
  tipo         text        NOT NULL,
  sucursal     text        NOT NULL,
  nombre       text        NOT NULL,
  telefono     text        NOT NULL,
  correo       text,
  fecha        date        NOT NULL,
  hora         text,
  fecha_salida date,
  personas     integer     NOT NULL,
  total        integer     NOT NULL,
  a_pagar      integer     NOT NULL,
  estado       text        NOT NULL DEFAULT 'pendiente',
  nota         text,
  nota_interna text,
  origen       text        NOT NULL DEFAULT 'web',
  creado       timestamptz NOT NULL DEFAULT now(),
  actualizado  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS reservas_fecha ON reservas (tipo, fecha);

-- Dos reservas activas de la cabaña nunca pueden compartir una noche,
-- aunque lleguen al mismo tiempo.
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'cabana_sin_traslape') THEN
    ALTER TABLE reservas ADD CONSTRAINT cabana_sin_traslape
      EXCLUDE USING gist (daterange(fecha, fecha_salida) WITH &&)
      WHERE (tipo = 'cabana' AND estado IN ('pendiente', 'confirmada'));
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS sesiones (
  token  text PRIMARY KEY,
  creado timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS ajustes (
  clave text PRIMARY KEY,
  valor text NOT NULL
);

-- Supabase publica las tablas del esquema "public" en su API REST con la llave anon.
-- Con RLS activo y sin políticas, esa API no puede leer ni escribir nada:
-- todo pasa por el servidor, que valida y recalcula precios.
ALTER TABLE mesas         ENABLE ROW LEVEL SECURITY;
ALTER TABLE categorias    ENABLE ROW LEVEL SECURITY;
ALTER TABLE platillos     ENABLE ROW LEVEL SECURITY;
ALTER TABLE pedidos       ENABLE ROW LEVEL SECURITY;
ALTER TABLE pedido_lineas ENABLE ROW LEVEL SECURITY;
ALTER TABLE llamadas      ENABLE ROW LEVEL SECURITY;
ALTER TABLE reservas      ENABLE ROW LEVEL SECURITY;
ALTER TABLE sesiones      ENABLE ROW LEVEL SECURITY;
ALTER TABLE ajustes       ENABLE ROW LEVEL SECURITY;
